function adjust_display_cost()
    for _, value in pairs(RANDOMIZED_PRICES) do
        local obj = Tracker:FindObjectForCode(string.format("@%s", value[1]))
        if obj then
            obj.AvailableChestCount = value[2]
        end
    end
end

function set_default_prices()
    for _, value in pairs(DEFAULT_SHOP_PRICES) do
        local obj = Tracker:FindObjectForCode(string.format("@%s", value[2]))
        if obj then
            obj.AvailableChestCount = value[1]
        end
    end
end